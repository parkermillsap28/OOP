number1 = int(input("Please enter first number"))
operator = input("Please enter operator")
number2 = int(input("Please enter second number"))
if operator == "+":
    c = number1 + number2
    print(c)
elif operator == "-":
    c = number1 - number2
    print(c)
elif operator == "*":
    c = number1 * number2
    print(c)
elif operator == "/":
    c = number1 / number2
    print(c)
